-- =====================================================================
--  Abu El Fadl Call Center — functions (FOR REVIEW — NOT APPLIED ANYWHERE)
--
--  All writes go through these functions. The app never sends prices:
--  cc_create_order reads every price from products_master and every
--  delivery fee from cc_delivery_areas inside the database.
-- =====================================================================

-- Role of the signed-in user ('agent' | 'supervisor'), or null if not active staff.
create or replace function public.cc_my_role()
returns text
language sql stable security definer
set search_path = public
as $$
  select role from public.cc_staff where user_id = auth.uid() and active
$$;

-- ---------------------------------------------------------------------
-- Create an order.
--   p_client_request_id : generated by the app once per draft; repeating
--                         the call (double click, retry) returns the
--                         same order instead of creating a second one.
--   p_customer : {"id": uuid, "order_phone"?: text}
--             or {"name": text, "phone": text, "phone2"?: text}
--   p_address  : {"id": uuid}
--             or {"area_id": uuid, "street", "building", "floor"?, "apartment"?, "landmark"?, "notes"?}
--   p_items    : [{"sku": text, "qty": int, "note"?: text}
--               | {"sku": text, "weight_grams": int, "note"?: text}, ...]
--   Any "price" sent by the app is ignored.
-- ---------------------------------------------------------------------
create or replace function public.cc_create_order(
  p_client_request_id uuid,
  p_source            text,
  p_customer          jsonb,
  p_address           jsonb,
  p_items             jsonb,
  p_note              text default null
)
returns public.cc_orders
language plpgsql security definer
set search_path = public
as $$
declare
  v_uid      uuid := auth.uid();
  v_staff    public.cc_staff;
  v_order    public.cc_orders;
  v_customer public.cc_customers;
  v_address  public.cc_addresses;
  v_area     public.cc_delivery_areas;
  v_phone    text;
  v_item     jsonb;
  v_prod     record;
  v_qty      int;
  v_grams    int;
  v_total    numeric(12,2);
  v_subtotal numeric(12,2) := 0;
  v_est      boolean := false;
  v_lines    jsonb := '[]'::jsonb;
  v_line_no  int := 0;
begin
  select * into v_staff from public.cc_staff where user_id = v_uid and active;
  if not found then
    raise exception 'غير مصرح' using errcode = '42501';
  end if;

  if p_client_request_id is null then
    raise exception 'client_request_id مطلوب' using errcode = '22023';
  end if;

  -- Idempotency: same draft submitted again → return the existing order.
  select * into v_order from public.cc_orders where client_request_id = p_client_request_id;
  if found then
    return v_order;
  end if;

  if p_source is null or p_source not in ('phone', 'whatsapp', 'facebook') then
    raise exception 'مصدر الطلب غير صحيح' using errcode = '22023';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array'
     or jsonb_array_length(p_items) = 0
     or jsonb_array_length(p_items) > 100 then
    raise exception 'السلة فارغة أو غير صحيحة' using errcode = '22023';
  end if;

  -- Customer: existing by id, or new.
  if p_customer ? 'id' then
    select * into v_customer from public.cc_customers where id = (p_customer->>'id')::uuid;
    if not found then
      raise exception 'العميل غير موجود' using errcode = 'P0002';
    end if;
    v_phone := coalesce(nullif(p_customer->>'order_phone', ''), v_customer.phone);
    if v_phone not in (v_customer.phone, coalesce(v_customer.phone2, '')) then
      raise exception 'رقم التواصل لا يخص هذا العميل' using errcode = '22023';
    end if;
  else
    begin
      insert into public.cc_customers (name, phone, phone2, created_by)
      values (btrim(p_customer->>'name'), p_customer->>'phone', nullif(p_customer->>'phone2', ''), v_uid)
      returning * into v_customer;
    exception when unique_violation then
      raise exception 'رقم الموبايل مسجل لعميل آخر' using errcode = '23505';
    end;
    v_phone := v_customer.phone;
  end if;

  -- Address: existing (must belong to this customer), or new.
  if p_address ? 'id' then
    select * into v_address from public.cc_addresses
     where id = (p_address->>'id')::uuid and customer_id = v_customer.id;
    if not found then
      raise exception 'العنوان غير موجود لهذا العميل' using errcode = 'P0002';
    end if;
  else
    insert into public.cc_addresses (customer_id, area_id, street, building, floor, apartment, landmark, notes, created_by)
    values (v_customer.id, (p_address->>'area_id')::uuid, btrim(p_address->>'street'), btrim(p_address->>'building'),
            nullif(p_address->>'floor', ''), nullif(p_address->>'apartment', ''),
            nullif(p_address->>'landmark', ''), nullif(p_address->>'notes', ''), v_uid)
    returning * into v_address;
  end if;

  -- Delivery fee comes from the area table, never from the app.
  select * into v_area from public.cc_delivery_areas where id = v_address.area_id;
  if not found or not v_area.active then
    raise exception 'منطقة التوصيل غير متاحة' using errcode = '22023';
  end if;

  -- Lines: price from products_master; weight lines = price-per-kg × grams / 1000.
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_line_no := v_line_no + 1;

    select sku, name, coalesce(price, 0)::numeric(12,2) as price
      into v_prod
      from public.products_master
     where sku = v_item->>'sku';
    if not found then
      raise exception 'صنف غير موجود: %', v_item->>'sku' using errcode = 'P0002';
    end if;

    v_qty   := (v_item->>'qty')::int;
    v_grams := (v_item->>'weight_grams')::int;
    if (v_qty is null) = (v_grams is null) then
      raise exception 'السطر % لازم يكون بالكمية أو بالوزن', v_line_no using errcode = '22023';
    end if;
    if v_qty is not null and v_qty not between 1 and 999 then
      raise exception 'الكمية غير صحيحة في السطر %', v_line_no using errcode = '22023';
    end if;
    if v_grams is not null and v_grams not between 10 and 20000 then
      raise exception 'الوزن غير صحيح في السطر %', v_line_no using errcode = '22023';
    end if;

    if v_grams is not null then
      v_total := round(v_prod.price * v_grams / 1000.0, 2);
      v_est := true;
    else
      v_total := round(v_prod.price * v_qty, 2);
    end if;
    v_subtotal := v_subtotal + v_total;

    v_lines := v_lines || jsonb_build_object(
      'line_no', v_line_no, 'sku', v_prod.sku, 'product_name', v_prod.name,
      'unit_price', v_prod.price, 'qty', v_qty, 'weight_grams', v_grams,
      'line_total', v_total, 'note', left(nullif(btrim(v_item->>'note'), ''), 120));
  end loop;

  begin
    insert into public.cc_orders (
      client_request_id, created_by, created_by_name, source,
      customer_id, customer_name, customer_phone,
      address_id, area_id, area_name, street, building, floor, apartment, landmark, address_notes,
      delivery_fee, subtotal, total, is_estimated, note)
    values (
      p_client_request_id, v_uid, v_staff.display_name, p_source,
      v_customer.id, v_customer.name, v_phone,
      v_address.id, v_area.id, v_area.name, v_address.street, v_address.building, v_address.floor,
      v_address.apartment, v_address.landmark, v_address.notes,
      v_area.fee, v_subtotal, v_subtotal + v_area.fee, v_est, left(nullif(btrim(p_note), ''), 300))
    returning * into v_order;
  exception when unique_violation then
    -- Two identical submissions raced: return the one that won.
    select * into v_order from public.cc_orders where client_request_id = p_client_request_id;
    if found then
      return v_order;
    end if;
    raise;
  end;

  insert into public.cc_order_items (order_id, line_no, sku, product_name, unit_price, qty, weight_grams, line_total, note)
  select v_order.id, l.line_no, l.sku, l.product_name, l.unit_price, l.qty, l.weight_grams, l.line_total, l.note
    from jsonb_to_recordset(v_lines) as l(
      line_no int, sku text, product_name text, unit_price numeric, qty int,
      weight_grams int, line_total numeric, note text);

  insert into public.cc_order_events (order_id, status, by, by_name)
  values (v_order.id, 'new', v_uid, v_staff.display_name);

  return v_order;
end;
$$;

-- ---------------------------------------------------------------------
-- Cancel an order (supervisor only, reason required, only from 'new').
-- ---------------------------------------------------------------------
create or replace function public.cc_cancel_order(p_order_id uuid, p_reason text)
returns public.cc_orders
language plpgsql security definer
set search_path = public
as $$
declare
  v_staff public.cc_staff;
  v_order public.cc_orders;
begin
  select * into v_staff from public.cc_staff where user_id = auth.uid() and active;
  if not found or v_staff.role <> 'supervisor' then
    raise exception 'إلغاء الطلب للمشرف فقط' using errcode = '42501';
  end if;
  if p_reason is null or length(btrim(p_reason)) = 0 then
    raise exception 'سبب الإلغاء مطلوب' using errcode = '22023';
  end if;

  update public.cc_orders
     set status = 'cancelled', cancelled_at = now(), cancelled_by = v_staff.user_id,
         cancelled_by_name = v_staff.display_name, cancel_reason = left(btrim(p_reason), 200)
   where id = p_order_id and status = 'new'
  returning * into v_order;
  if not found then
    raise exception 'الطلب غير موجود أو ملغي بالفعل' using errcode = 'P0002';
  end if;

  insert into public.cc_order_events (order_id, status, by, by_name, reason)
  values (v_order.id, 'cancelled', v_staff.user_id, v_staff.display_name, v_order.cancel_reason);
  return v_order;
end;
$$;

-- ---------------------------------------------------------------------
-- Add or edit a delivery area (supervisor only). p_id null = new area.
-- ---------------------------------------------------------------------
create or replace function public.cc_save_area(p_id uuid, p_name text, p_fee numeric, p_active boolean)
returns public.cc_delivery_areas
language plpgsql security definer
set search_path = public
as $$
declare
  v_area public.cc_delivery_areas;
begin
  if public.cc_my_role() is distinct from 'supervisor' then
    raise exception 'تعديل المناطق للمشرف فقط' using errcode = '42501';
  end if;
  if p_name is null or length(btrim(p_name)) = 0 or p_fee is null or p_fee < 0 then
    raise exception 'اسم المنطقة والرسوم مطلوبين' using errcode = '22023';
  end if;

  if p_id is null then
    insert into public.cc_delivery_areas (name, fee, active, updated_by)
    values (btrim(p_name), round(p_fee, 2), coalesce(p_active, true), auth.uid())
    returning * into v_area;
  else
    update public.cc_delivery_areas
       set name = btrim(p_name), fee = round(p_fee, 2), active = coalesce(p_active, active),
           updated_at = now(), updated_by = auth.uid()
     where id = p_id
    returning * into v_area;
    if not found then
      raise exception 'المنطقة غير موجودة' using errcode = 'P0002';
    end if;
  end if;
  return v_area;
end;
$$;
