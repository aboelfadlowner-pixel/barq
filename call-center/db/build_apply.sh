#!/usr/bin/env bash
# Builds apply_cc.sql = 01 + 02 + 03 wrapped in ONE transaction (L2).
# If any statement fails, nothing is applied. Re-running is safe.
set -euo pipefail
cd "$(dirname "$0")"
{
  echo "-- GENERATED by db/build_apply.sh from 01_schema.sql, 02_functions.sql, 03_security.sql, 04_agents.sql, 05_sale_unit.sql, 06_signup_code.sql, 07_categories.sql, 08_roles.sql, 09_prep.sql, 10_edit_order.sql, 11_driver.sql, 12_active_products.sql, 13_modifiers.sql, 14_account_names.sql, 15_customer_profile.sql, 16_blocked_numbers.sql, 17_admin_unblock.sql, 18_driver_tracking.sql — do not edit."
  echo "-- FOR REVIEW — run only after approval, as the postgres role (SQL editor / migration)."
  echo "begin;"
  echo "set local lock_timeout = '5s';"
  echo "set local client_min_messages = warning;"
  echo "set local statement_timeout = '60s';"
  for f in 01_schema.sql 02_functions.sql 03_security.sql 04_agents.sql 05_sale_unit.sql 06_signup_code.sql 07_categories.sql 08_roles.sql 09_prep.sql 10_edit_order.sql 11_driver.sql 12_active_products.sql 13_modifiers.sql 14_account_names.sql 15_customer_profile.sql 16_blocked_numbers.sql 17_admin_unblock.sql 18_driver_tracking.sql; do
    echo; echo "-- ===== $f ====="; cat "$f"
  done
  echo; echo "commit;"
} > apply_cc.sql
echo "apply_cc.sql written"
