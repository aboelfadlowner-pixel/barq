-- Abu El Fadl online store: first database migration (applied 2026-10-20 to the main project).
--
-- Everything the website owns lives in its own schema, "store", next to the tools that already use this project.
-- Nothing outside "store" is created, changed or dropped. The only link to the other tools is one read-only view of
-- product prices (store.master_prices over public.products_master), kept to three columns so the website does not
-- depend on the rest of that table.
--
-- The website connects as its own role, store_app, which can work in "store" and nothing else. The schema is not
-- exposed through the Supabase API (only "public" is), so the browser and the anon key never reach it.
--
-- Undo (drops the website's data, touches nothing else):
--   drop schema store cascade; drop role store_app;

begin;

create schema store;

-- updated_at on every change
create function store.touch() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- ---------------------------------------------------------------------------------------------------------------
-- Catalog
-- ---------------------------------------------------------------------------------------------------------------

-- Website categories, in display order. id is the slug in /category/<id>.
create table store.categories (
  id         text primary key check (id ~ '^[a-z0-9-]{2,30}$'),
  name       text not null check (length(name) between 2 and 60),
  position   int  not null default 0,
  art        text not null default 'a-bowl',
  tint       text not null default '#EEF6EC',
  image_url  text,
  icon_url   text,
  tagline    text check (length(tagline) <= 80),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger categories_touch before update on store.categories for each row execute function store.touch();

-- Website products. Linked to the products sheet by SKU: the price comes from public.products_master
-- (see store.catalog). "price" is used only while a product has no SKU yet.
create table store.products (
  id          bigint generated by default as identity primary key,
  sku         text unique check (sku ~ '^sk-[0-9]+$'),
  category_id text not null references store.categories (id) on update cascade,
  name        text not null check (length(name) between 2 and 120),
  price       numeric(10, 2) check (price >= 0),
  weighed     boolean not null default false,
  weight_step numeric(6, 3) check (weight_step > 0),
  min_weight  numeric(6, 3) check (min_weight > 0),
  max_weight  numeric(6, 3) check (max_weight > 0),
  in_stock    boolean not null default true,
  bestseller  boolean not null default false,
  offer       boolean not null default false,
  sale_price  numeric(10, 2) check (sale_price >= 0),
  offer_start date,
  offer_end   date,
  description text,
  image_url   text,
  position    int not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  check (offer_end is null or offer_start is null or offer_end >= offer_start)
);
create index products_category_position on store.products (category_id, position);
create trigger products_touch before update on store.products for each row execute function store.touch();

-- The only window onto the other tools' data: SKU, name and price of the products sheet, read-only.
-- The view runs with its owner's rights, so store_app reads it without any right on products_master itself.
create view store.master_prices as
  select sku, name, price, updated_at
  from public.products_master
  where sku ~ '^sk-[0-9]+$';

-- Products with the price the store charges: the sheet price for linked products (hidden when the sheet has no
-- price for that SKU), the product's own price otherwise.
create view store.catalog as
  select p.*,
         case when p.sku is null then p.price else nullif(m.price, 0) end as current_price,
         m.name       as master_name,
         m.updated_at as price_updated_at,
         (p.sku is not null and m.sku is null) as missing_from_sheet
  from store.products p
  left join store.master_prices m on m.sku = p.sku;

-- Photos uploaded from the dashboard (resized to ~1000 px WebP in the browser, so tens of KB each).
create table store.images (
  name       text primary key check (name ~ '^[a-z0-9-]+\.(webp|jpg|png)$'),
  mime       text not null check (mime in ('image/webp', 'image/jpeg', 'image/png')),
  data       bytea not null check (octet_length(data) <= 5 * 1024 * 1024),
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------------------------------------------

create sequence store.order_number_seq;

create table store.orders (
  id             bigint generated always as identity primary key,
  number         text not null unique default ('AF-' || lpad(nextval('store.order_number_seq')::text, 5, '0')),
  customer_name  text not null check (length(customer_name) between 2 and 80),
  customer_phone text not null check (customer_phone ~ '^01[0125][0-9]{8}$'),
  address        text not null check (length(address) between 5 and 300),
  note           text not null default '' check (length(note) <= 300),
  delivery_area  text,
  delivery_fee   numeric(10, 2) not null default 0 check (delivery_fee >= 0),
  subtotal       numeric(10, 2) not null check (subtotal >= 0),
  total          numeric(10, 2) not null check (total >= 0),
  payment_method text not null default 'cash' check (payment_method in ('cash', 'card')),
  status         text not null default 'new'
                 check (status in ('new', 'preparing', 'out_for_delivery', 'delivered', 'cancelled')),
  staff_note     text not null default '' check (length(staff_note) <= 500),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index orders_created on store.orders (created_at desc);
create index orders_phone on store.orders (customer_phone);
create trigger orders_touch before update on store.orders for each row execute function store.touch();

-- Order lines keep a copy of the name and price at order time, so later price changes never alter old orders.
-- No foreign key to products: deleting a product keeps its past orders intact.
create table store.order_items (
  id         bigint generated always as identity primary key,
  order_id   bigint not null references store.orders (id) on delete cascade,
  product_id bigint,
  sku        text,
  name       text not null,
  price      numeric(10, 2) not null check (price >= 0),
  weighed    boolean not null,
  quantity   numeric(10, 3) not null check (quantity > 0),
  line_total numeric(10, 2) not null check (line_total >= 0)
);
create index order_items_order on store.order_items (order_id);

-- ---------------------------------------------------------------------------------------------------------------
-- Settings and login guard
-- ---------------------------------------------------------------------------------------------------------------

-- One row: hours, delivery areas, contact details, pause switch... (the StoreSettings object of the app).
create table store.settings (
  id         smallint primary key default 1 check (id = 1),
  data       jsonb not null default '{}',
  updated_at timestamptz not null default now()
);
insert into store.settings (id) values (1);
create trigger settings_touch before update on store.settings for each row execute function store.touch();

-- Wrong dashboard passwords per address (5 in 15 minutes lock the address for 15 minutes).
create table store.login_fails (
  key          text primary key,
  failures     int not null default 0,
  since        timestamptz not null default now(),
  locked_until timestamptz
);

-- ---------------------------------------------------------------------------------------------------------------
-- The website's own database role
-- ---------------------------------------------------------------------------------------------------------------

-- Created without a password: the owner sets it in the Supabase SQL editor and puts it in the Vercel settings.
-- It never appears in code or in chat.
create role store_app login noinherit connection limit 20;
alter role store_app set statement_timeout = '10s';
alter role store_app set search_path = store;

revoke all on schema store from public;
grant usage on schema store to store_app;
grant select, insert, update, delete on all tables in schema store to store_app;
grant usage, select on all sequences in schema store to store_app;

-- Read-only on the price view and the catalog built from it.
revoke insert, update, delete on store.master_prices, store.catalog from store_app;

commit;
