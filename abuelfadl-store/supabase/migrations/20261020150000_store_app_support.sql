-- What the website's database layer needs (src/server/db-postgres.ts). Changes the "store" schema only. Applied 2026-10-20.

-- The app numbers orders itself (id and "AF-00001" from the same counter, as before), so it supplies the id.
alter table store.orders alter column id set generated by default;

-- Same limits as the app: customer note up to 500 characters, staff note up to 1000.
alter table store.orders drop constraint orders_note_check, add constraint orders_note_check check (length(note) <= 500);
alter table store.orders drop constraint orders_staff_note_check, add constraint orders_staff_note_check check (length(staff_note) <= 1000);

-- Catalog version: bumped by any change to categories, products or settings, so each server instance reloads its
-- cached catalog only when something changed (one tiny query per request instead of reloading everything).
create table store.meta (
  id              smallint primary key default 1 check (id = 1),
  catalog_version bigint not null default 0
);
insert into store.meta (id) values (1);

-- security definer: store_app only reads store.meta; the trigger itself does the update.
create function store.bump_catalog_version() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update store.meta set catalog_version = catalog_version + 1 where id = 1;
  return null;
end $$;

create trigger categories_version after insert or update or delete on store.categories
  for each statement execute function store.bump_catalog_version();
create trigger products_version after insert or update or delete on store.products
  for each statement execute function store.bump_catalog_version();
create trigger settings_version after insert or update or delete on store.settings
  for each statement execute function store.bump_catalog_version();

grant select on store.meta to store_app;
revoke execute on function store.bump_catalog_version() from public;
