// Writes the SQL that fills the database "store" schema with the starting catalog: the categories and products of the
// current store data (src/data + seed.ts upgrades) and the default dashboard settings. Prices of products with a SKU
// are not copied: the database takes them from the products sheet.
//
//   node scripts/seed-sql.mjs > /path/to/seed.sql
//
// The SQL only inserts into store.categories, store.products and store.settings, and refuses to run when the catalog
// is not empty (so it can never overwrite what was edited from the dashboard).
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const entry = `
import { seedStore } from "./src/server/seed";
import { DEFAULT_SETTINGS } from "./src/lib/settings";
const data = seedStore();
console.log(JSON.stringify({
  categories: data.categories.map((c, i) => ({
    id: c.id, name: c.name, position: i, art: c.art, tint: c.tint,
    image_url: c.imageUrl || null, icon_url: c.iconUrl || null, tagline: c.tagline || null,
  })),
  products: data.products.map((p, i) => ({
    id: p.id, sku: p.sku ?? null, category_id: p.categoryId, name: p.name, price: p.sku ? null : p.price,
    weighed: p.weighed, weight_step: p.weightStep ?? null, min_weight: p.minWeight ?? null, max_weight: p.maxWeight ?? null,
    in_stock: p.inStock, bestseller: p.bestseller, offer: p.offer, sale_price: p.salePrice ?? null,
    offer_start: p.offerStart ?? null, offer_end: p.offerEnd ?? null, description: p.description ?? null,
    image_url: p.imageUrl ?? null, position: i,
  })),
  settings: DEFAULT_SETTINGS,
}));
`;

const result = await build({
  stdin: { contents: entry, resolveDir: root, loader: "ts" },
  bundle: true,
  platform: "node",
  format: "esm",
  write: false,
  alias: { "@": path.join(root, "src") },
  logLevel: "error",
});
const code = result.outputFiles[0].text;
const { default: vm } = await import("node:vm");
let out = "";
vm.runInNewContext(code, { console: { log: (text) => (out += text) } });
const data = JSON.parse(out);

const json = (value) => {
  const text = JSON.stringify(value);
  if (text.includes("$seed$")) throw new Error("unexpected $seed$ in data");
  return `$seed$${text}$seed$::jsonb`;
};

console.log(`-- Starting catalog for the website (generated by scripts/seed-sql.mjs): ${data.categories.length} categories, ${data.products.length} products.
do $$ begin
  if exists (select 1 from store.categories) or exists (select 1 from store.products) then
    raise exception 'store catalog is not empty: nothing inserted';
  end if;
end $$;

insert into store.categories (id, name, position, art, tint, image_url, icon_url, tagline)
select id, name, position, art, tint, image_url, icon_url, tagline
from jsonb_to_recordset(${json(data.categories)})
  as x(id text, name text, position int, art text, tint text, image_url text, icon_url text, tagline text);

insert into store.products (id, sku, category_id, name, price, weighed, weight_step, min_weight, max_weight, in_stock,
                            bestseller, offer, sale_price, offer_start, offer_end, description, image_url, position)
select id, sku, category_id, name, price, weighed, weight_step, min_weight, max_weight, in_stock,
       bestseller, offer, sale_price, offer_start, offer_end, description, image_url, position
from jsonb_to_recordset(${json(data.products)})
  as x(id bigint, sku text, category_id text, name text, price numeric, weighed boolean, weight_step numeric,
       min_weight numeric, max_weight numeric, in_stock boolean, bestseller boolean, offer boolean, sale_price numeric,
       offer_start date, offer_end date, description text, image_url text, position int);

-- New products created from the dashboard continue after the highest id.
select setval(pg_get_serial_sequence('store.products', 'id'), (select max(id) from store.products));

update store.settings set data = ${json(data.settings)} where id = 1 and data = '{}'::jsonb;`);
